// Build-time brand fetcher.
// Run `node scripts/fetch-ticketmaster-brand.mjs` (wired as npm `prebuild`) to refresh
// src/app/tm-brand.ts with Ticketmaster's live <title>, description, og:image and favicon.
// No runtime network calls: layout.tsx imports the generated static values.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = resolve(fileURLToPath(import.meta.url), '..');
const OUT = resolve(__dirname, '../src/app/tm-brand.ts');

const TARGET = 'https://www.ticketmaster.com/';
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) ' +
  'Chrome/124.0.0.0 Safari/537.36';

let html;
try {
  const res = await fetch(TARGET, { headers: { 'user-agent': UA }, redirect: 'follow' });
  if (!res.ok) throw new Error(`ticketmaster.com returned HTTP ${res.status}`);
  html = await res.text();
} catch (e) {
  console.warn(
    `fetch-ticketmaster-brand: live fetch failed (${e instanceof Error ? e.message : String(e)}); keeping committed src/app/tm-brand.ts`
  );
  process.exit(0);
}

const firstMatch = (re) => {
  const m = html.match(re);
  return m ? m[1] : '';
};

const title = firstMatch(/<title[^>]*>([^<]*)<\/title>/i) || 'Ticketmaster';
const description =
  firstMatch(/<meta[^>]+name=["']description["'][^>]+content=["']([^"']*)["']/i) ||
  firstMatch(/<meta[^>]+content=["']([^"']*)["'][^>]+name=["']description["']/i) ||
  '';
const favicon =
  firstMatch(/<link[^>]+rel=["']icon["'][^>]+href=["']([^"']*)["']/i) ||
  firstMatch(/<link[^>]+href=["']([^"']*)["'][^>]+rel=["']icon["']/i) ||
  firstMatch(/<link[^>]+rel=["'](?:shortcut icon|shortcut)["'][^>]+href=["']([^"']*)["']/i) ||
  firstMatch(/<link[^>]+href=["']([^"']*)["'][^>]+rel=["'](?:shortcut icon|shortcut)["']/i) ||
  'https://www.ticketmaster.com/favicon.ico';

const abs = (u) => {
  try {
    return new URL(u, TARGET).toString();
  } catch {
    return u;
  }
};

const iconUrl = abs(favicon || 'https://www.ticketmaster.com/favicon.ico');

const ts = `// AUTO-GENERATED by scripts/fetch-ticketmaster-brand.mjs — do not edit.
// Refreshed on each prebuild. Source: ${TARGET}
export const TM_BRAND = {
  title: ${JSON.stringify(title)},
  description: ${JSON.stringify(description)},
  icon: ${JSON.stringify(iconUrl)},
} as const;
`;

writeFileSync(OUT, ts);
console.log('Wrote', OUT);
console.log('title      :', title);
console.log('description:', description);
console.log('favicon    :', iconUrl);
